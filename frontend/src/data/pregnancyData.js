export function getWeekData(weekNumber) {
  const safeWeek = Math.max(1, Math.min(40, Math.round(weekNumber || 24)));
  return pregnancyWeeks[safeWeek - 1] || pregnancyWeeks[23];
}

export function calculatePregnancyWeek(dueDateStr) {
  if (!dueDateStr) return { week: 24, daysRemaining: 112, trimester: 2 };
  const due = new Date(dueDateStr);
  const now = new Date();
  const diffTime = due.getTime() - now.getTime();
  const daysRemaining = Math.max(0, Math.ceil(diffTime / (1000 * 60 * 60 * 24)));
  const totalDays = 280; // 40 weeks
  const elapsedDays = Math.max(0, totalDays - daysRemaining);
  const week = Math.min(40, Math.max(1, Math.floor(elapsedDays / 7) + 1));
  const trimester = week <= 13 ? 1 : week <= 27 ? 2 : 3;
  return { week, daysRemaining, trimester };
}
